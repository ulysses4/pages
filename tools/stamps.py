#!/usr/bin/env python3
"""Content-change stamps for the pages site.

PDFs regenerated by cron get new bytes every run (embedded creation
timestamps) even when the rendered tables are identical, so mtimes and
byte-hashes say "changed" when nothing did. fingerprint() hashes what the
reader actually sees: PDFs are rasterized (ghostscript, 50dpi grayscale)
before hashing; other files hash raw. stamp() keeps {fingerprint, when}
per site in ~/.pages_stamps.json and only advances `when` on a real
content change — builders show that time and exit 3 when nothing changed.
"""

import hashlib
import json
import os
import subprocess
from datetime import datetime

STATE = os.path.expanduser("~/.pages_stamps.json")


def _file_fp(path):
    if path.lower().endswith(".pdf"):
        try:
            out = subprocess.run(
                ["gs", "-q", "-dNOPAUSE", "-dBATCH", "-sDEVICE=gray",
                 "-r50", "-o", "-", path],
                capture_output=True, timeout=120).stdout
            if out:
                return hashlib.sha256(out).hexdigest()
        except Exception:
            pass
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def fingerprint(paths):
    h = hashlib.sha256()
    for p in sorted(paths):
        h.update(_file_fp(p).encode())
    return h.hexdigest()


def stamp(key, paths):
    """(datetime_of_last_content_change, changed_now: bool)"""
    fp = fingerprint(paths)
    try:
        state = json.load(open(STATE))
    except Exception:
        state = {}
    rec = state.get(key)
    if rec and rec.get("fp") == fp:
        return datetime.fromisoformat(rec["when"]), False
    # first sighting seeds from the newest file's mtime; later changes
    # use detection time (within a cron tick of the true change)
    when = (datetime.fromtimestamp(max(os.path.getmtime(p) for p in paths))
            if rec is None else datetime.now())
    state[key] = {"fp": fp, "when": when.isoformat(timespec="seconds")}
    tmp = STATE + ".tmp"
    json.dump(state, open(tmp, "w"), indent=1)
    os.replace(tmp, STATE)
    return when, True
